def test_phase5_video_audio_pdf_corrupted_large_and_restart_integrity(tmp_path: Path):
    # 1. Video (MP4 / MOV ISOBMFF with moov/udta AI marker)
    ftyp = b"\x00\x00\x00\x14ftypisom\x00\x00\x02\x00isom"
    udta_payload = b"Generated by Sora OpenAI Video"
    udta_box = struct.pack(">I", len(udta_payload) + 8) + b"udta" + udta_payload
    moov_box = struct.pack(">I", len(udta_box) + 8) + b"moov" + udta_box
    mdat_payload = b"\x11\x22\x33\x44" * 16
    mdat_box = struct.pack(">I", len(mdat_payload) + 8) + b"mdat" + mdat_payload
    mp4_bytes = ftyp + moov_box + mdat_box

    src_mp4 = tmp_path / "clip.mp4"
    src_mp4.write_bytes(mp4_bytes)

    insp_mp4 = inspect_file_comprehensive(path=src_mp4)
    assert insp_mp4["kind"] == "av"
    assert insp_mp4["detected_format"] == "mp4"
    assert insp_mp4["provenance"]["has_ai_metadata"] is True

    clean_mp4 = process_clean_file(path=src_mp4)
    assert clean_mp4["ok"] is True
    assert clean_mp4["changed"] is True
    # Original file integrity must be preserved untouched on disk
    assert src_mp4.read_bytes() == mp4_bytes
    out_mp4_path = Path(clean_mp4["output_location"])
    assert out_mp4_path.is_file()
    assert out_mp4_path.name == "clip.originclean.mp4"
    cleaned_mp4_bytes = out_mp4_path.read_bytes()
    assert b"OpenAI" not in cleaned_mp4_bytes
    assert mdat_payload in cleaned_mp4_bytes

    # 2. PDF Document inspection, metadata edit, and cleaning
    pdf_bytes = (
        b"%PDF-1.4\n"
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
        b"2 0 obj\n<< /Type /Pages /Kids [] /Count 0 >>\nendobj\n"
        b"3 0 obj\n<< /Title (Draft Doc) /Creator (ChatGPT AI) /Author (Anon) >>\nendobj\n"
        b"trailer\n<< /Root 1 0 R /Info 3 0 R >>\n%%EOF\n"
    )
    insp_pdf = inspect_file_comprehensive(data=pdf_bytes, filename="report.pdf")
    assert insp_pdf["detected_format"] == "pdf"
    edited_pdf, pdf_acts = edit_metadata_bytes(
        pdf_bytes, "report.pdf", {"Title": "OriginClean Final", "Author": "Muhammad Lutfi Muzaki"}
    )
    assert any("Title" in a for a in pdf_acts)
    assert b"OriginClean Final" in edited_pdf

    # 3. Corrupted / Truncated file handling (preserves recoverable tail without crashing)
    truncated_png = _make_sample_png(with_ai_text=True)[:48]
    insp_trunc = inspect_file_comprehensive(data=truncated_png, filename="broken.png")
    assert insp_trunc["ok"] is True

    # 4. Large file limit enforcement via settings
    update_settings({"max_file_size_mb": 1})
    oversized_bytes = b"A" * (1024 * 1024 + 512)
    with pytest.raises(ValueError, match="exceeds limit"):
        process_clean_file(data=oversized_bytes, filename="oversized.txt")
    reset_settings()

    # 5. Application restart persistence check (re-querying SQLite DB from fresh calls)
    stats_before_restart = get_dashboard_stats()
    assert stats_before_restart["total_files_processed"] >= 1
    history_after_restart = list_history(search="clip.mp4")
    assert len(history_after_restart) == 1
    assert history_after_restart[0]["output_filename"] == "clip.originclean.mp4"


