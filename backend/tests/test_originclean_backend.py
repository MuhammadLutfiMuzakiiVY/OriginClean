def _make_sample_png(*, with_ai_text: bool = True, with_c2pa: bool = False) -> bytes:
    ihdr = struct.pack(">IIBBBBB", 4, 4, 8, 2, 0, 0, 0)
    raw_scanlines = b"\x00" + (b"\xff\x00\x00" * 4)
    idat = zlib.compress(raw_scanlines * 4)
    chunks = [_png_chunk(b"IHDR", ihdr)]
    if with_ai_text:
        chunks.append(_png_chunk(b"tEXt", b"Software\x00Generated by OpenAI DALL-E"))
        chunks.append(_png_chunk(b"tEXt", b"Author\x00Original Photographer"))
    if with_c2pa:
        chunks.append(_png_chunk(b"caBX", b"c2pa-manifest-jumbf-payload"))
    chunks.append(_png_chunk(b"IDAT", idat))
    chunks.append(_png_chunk(b"IEND", b""))
    return PNG_SIG + b"".join(chunks)


def _make_sample_wav() -> bytes:
    fmt_payload = struct.pack("<HHIIHH", 1, 1, 8000, 16000, 2, 16)
    fmt_chunk = b"fmt " + struct.pack("<I", len(fmt_payload)) + fmt_payload
    info_inam = b"INAM" + struct.pack("<I", 10) + b"TestAudio\x00"
    info_isft = b"ISFT" + struct.pack("<I", 18) + b"Generated by Suno\x00"
    list_payload = b"INFO" + info_inam + info_isft
    list_chunk = b"LIST" + struct.pack("<I", len(list_payload)) + list_payload
    data_payload = b"\x00\x00" * 32
    data_chunk = b"data" + struct.pack("<I", len(data_payload)) + data_payload
    riff_body = b"WAVE" + fmt_chunk + list_chunk + data_chunk
    return b"RIFF" + struct.pack("<I", len(riff_body)) + riff_body


