def test_http_server_endpoints():
    server = ThreadingHTTPServer(("127.0.0.1", 0), OriginCleanHandler)
    port = server.server_port
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    base_url = f"http://127.0.0.1:{port}"
    try:
        with urllib.request.urlopen(f"{base_url}/api/v1/dashboard", timeout=5) as resp:
            dash = json.loads(resp.read().decode("utf-8"))
            assert dash["ok"] is True
            assert dash["app"]["name"] == "OriginClean"
            assert dash["app"]["developer"] == "Muhammad Lutfi Muzaki"

        req_body = json.dumps(
            {
                "name": "test.txt",
                "file": base64.b64encode("Clean\u200bMe".encode("utf-8")).decode("ascii"),
            }
        ).encode("utf-8")
        req = urllib.request.Request(
            f"{base_url}/api/v1/clean",
            data=req_body,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=5) as resp:
            clean_res = json.loads(resp.read().decode("utf-8"))
            assert clean_res["ok"] is True
            assert base64.b64decode(clean_res["cleaned"]) == b"CleanMe"
    finally:
        server.shutdown()
        server.server_close()


