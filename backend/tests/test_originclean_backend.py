def test_comprehensive_inspection_and_c2pa_protection():
    png_bytes = _make_sample_png(with_ai_text=True, with_c2pa=True)
    insp = inspect_file_comprehensive(data=png_bytes, filename="photo.png")
    assert insp["ok"] is True
    assert insp["kind"] == "image"
    assert insp["detected_format"] == "png"
    assert insp["provenance"]["has_c2pa"] is True
    assert insp["provenance"]["has_ai_metadata"] is True
    assert len(insp["signatures"]["sha256"]) == 64

    # 1. Default clean preserves C2PA while stripping AI tEXt chunk
    cleaned_default = process_clean_file(data=png_bytes, filename="photo.png")
    assert cleaned_default["ok"] is True
    assert cleaned_default["c2pa_preserved"] is True
    out_bytes = base64.b64decode(cleaned_default["cleaned"])
    assert b"caBX" in out_bytes
    assert b"OpenAI" not in out_bytes

    # 2. Attempting to remove C2PA without explicit authorization raises ProvenanceAuthorizationError
    with pytest.raises(ProvenanceAuthorizationError):
        process_clean_file(
            data=png_bytes,
            filename="photo.png",
            options={"preserve_c2pa": False, "allow_c2pa_removal": False},
        )

    # 3. Explicit authorization removes C2PA
    cleaned_authorized = process_clean_file(
        data=png_bytes,
        filename="photo.png",
        options={"preserve_c2pa": False, "allow_c2pa_removal": True},
    )
    out_bytes_no_c2pa = base64.b64decode(cleaned_authorized["cleaned"])
    assert b"caBX" not in out_bytes_no_c2pa


