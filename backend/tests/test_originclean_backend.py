    assert b"Suno" not in cleaned_wav["cleaned_bytes"]

    # Markdown frontmatter edit
    md_bytes = b"---\ntitle: Old\ngenerator: ChatGPT\n---\nBody content\n"
    edited_md, _ = edit_metadata_bytes(md_bytes, "doc.md", {"title": "New Title", "author": "Muhammad Lutfi Muzaki"})
